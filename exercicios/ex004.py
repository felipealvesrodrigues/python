var = input('Digite algo: ')
print('\033[4;33mO tipo primitivo desse valor é \033[m \033[32m', type(var))
print('\033[4;33mSó tem espaços?\033[m \033[32m', var.isspace())
print('\033[4;33mÉ um número?\033[m \033[32m', var.isnumeric())
print('\033[4;33mÉ alfabético?\033[m \033[32m', var.isalpha())
print('\033[4;33mÉ alfanumérico?\033[m \033[32m', var.isalnum())
print('\033[4;33mEstá em maiúsculas?\033[m \033[32m', var.isupper())
print('\033[4;33mEstá em minúsculas?\033[m \033[32m', var.islower())
print('\033[4;33mEstá capitalizada?\033[m \033[32m', var.istitle())
